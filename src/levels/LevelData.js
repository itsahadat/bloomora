/** Objective with every 'all' replaced by the real count from the layout. */
export function resolveObjective(level) {
  const counts = countLayout(level.layout);
  return Object.fromEntries(Object.entries(level.objective).map(([type, value]) => (
    [type, value === 'all' ? counts[type] ?? 0 : value]
  )));
}
