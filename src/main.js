import './style.css';
import Phaser from 'phaser';
import { BootScene } from './scenes/BootScene.js';
import { MenuScene } from './scenes/MenuScene.js';
import { GameScene } from './scenes/GameScene.js';
import { MapScene } from './scenes/MapScene.js';
import { Platform, TARGET } from './core/Platform.js';

function startGame() {
  return new Phaser.Game({
    type: Phaser.AUTO,
    parent: 'app',
    width: window.innerWidth,
    height: window.innerHeight,
    backgroundColor: '#dff1cc',
    scale: {
      mode: Phaser.Scale.RESIZE,
      autoCenter: Phaser.Scale.CENTER_BOTH,
    },
    render: {
      antialias: true,
      pixelArt: false,
      // The 512px art is drawn at ~54px; mipmaps keep it smooth instead of sparkly.
      mipmapFilter: 'LINEAR_MIPMAP_LINEAR',
    },
    // All audio is generated by our own WebAudio synth (core/Synth.js).
    audio: { noAudio: true },
    scene: [BootScene, MenuScene, MapScene, GameScene],
  });
}

// Wait (briefly) for the web font so Phaser text doesn't render with the fallback font.
const fontsReady = document.fonts
  ? Promise.all([
    document.fonts.load('700 32px "Fredoka"'),
    document.fonts.load('500 16px "Fredoka"'),
    document.fonts.load('400 32px "Lilita One"'),
  ])
  : Promise.resolve();

// The platform SDK (if any) must be ready before the first save is read.
const platformReady = Platform.init().then(() => Platform.loadingStart());

Promise.all([
  Promise.race([fontsReady, new Promise((resolve) => setTimeout(resolve, 1500))]).catch(() => {}),
  platformReady,
])
  .then(() => {
    const game = startGame();
    // Dev-only handle for debugging from the browser console.
    if (import.meta.env.DEV || new URLSearchParams(window.location.search).has('debug')) window.__bloomora = game;
  });

// Installable + offline play (production builds only, so dev reloads are never served stale).
// Not on portals (itch, CrazyGames): they show the game in a frame and a cache there would hold back updates.
if (import.meta.env.PROD && TARGET === 'web' && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('./sw.js').catch(() => {});
  });
}
